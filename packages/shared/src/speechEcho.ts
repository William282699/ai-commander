// ============================================================
// AI Commander — 复读谓词（唯一一份）
//
// 「这段要念出去的话，是不是把长官刚说的原话整句念了回去。」
//
// ★为什么是共享包里的**唯一一份导出**（Fable 裁定 2026-08-10）：
//   同一个判断要在三个地方用——客户端运行时的出声闸（planVoiceSpeech）、
//   服务端 `voice_heard` 日志的犯病计数、以及台架的记录行。三份拷贝就会漂，
//   而这一格漂了的后果是"台架说没病、耳朵里天天听见自己的话"。
//
// ★为什么改成引擎闸而不是改 prompt（同上裁定）：
//   真信封 N=20 实测 L7 红 6/20（净臂 0/7、脏臂 6/13）——**跟输入质量走**，
//   和 L2 同族。输入脏的时候模型除了确认还能说什么？这一格靠措辞管不住，
//   而它偏偏是**唯一会被念出来的那段文字**：分层这一层的核心承诺
//   （耳朵里不再出现你自己的话）就押在它上面。所以由引擎当场拦，不劳嘴。
//
// 门槛 4 字沿用 L2/L7 的既有口径：短句（"可以"/"撤退"）的包含关系太容易
// 巧合命中，把正常的短回令误判成复读。
// ============================================================

const MIN_ECHO_CHARS = 4;

/**
 * `text` 是否整句复读了 `heard`。
 *
 * 判的是**包含**不是相等：模型常在原话前后加一个「长官，」或句号，
 * 那仍然是把他的话念回给他。
 */
export function echoesHeard(text: string | undefined, heard: string | undefined): boolean {
  const t = (text ?? "").trim();
  const h = (heard ?? "").trim();
  if (h.length <= MIN_ECHO_CHARS || t.length === 0) return false;
  return t.includes(h);
}
